  function applyEff(s, e, ctx) {
    if (!e) return "";
    ctx = ctx || {};
    var out = [];
    STATS.forEach(function (k) { if (e[k]) stat(s, k, e[k]); });
    if (e.cash) cash(s, e.cash);
    if (e.cashM) cash(s, Math.round(e.cashM * incM(s)));
    if (e.cashPct) cash(s, Math.round(e.cashPct * Math.max(0, s.cash)));
    if (e.pocket) { var pm = D.wealth[s.wealth].pocket * ri(s, 1, 3); cash(s, pm); ctx.m = pm; }
    if (e.love && s.partner) { s.partner.love = clamp(s.partner.love + e.love, 0, 100); fx(s, "love", e.love); }
    if (e.flag) [].concat(e.flag).forEach(function (f) { setFlag(s, f); });
    if (e.unflag) [].concat(e.unflag).forEach(function (f) { delete s.flags[f]; });
    if (e.later) s.queue.push({ id: e.later[0], age: s.age + e.later[1] });
    if (e.perf && s.job) s.job.perf = clamp(s.job.perf + e.perf, -5, 10);
    if (e.raise && s.job) s.job.bonus = Math.min(2, s.job.bonus * e.raise);
    if (e.job === "lose") loseJob(s);
    if (e.job === "promote" && s.job) promote(s);
    if (e.job === "demote" && s.job && s.job.lvl > 0) { s.job.lvl--; }
    if (e.quit) loseJob(s);
    if (e.retire) { retire(s); ctx.m = s.pension; }
    if (e.dropout && s.study) { s.study = null; s.c.dropouts++; }
    if (e.uni) {
      if (e.uni === "paid") s.flags.uni_paid = s.age + 1;
      else delete s.flags.uni_paid;
      pushEvent(s, "faculty", true);
    }
    if (e.college) pushEvent(s, "college_pick", true);
    if (e.study) {
      var kind = e.study[0], fee = 0;
      if (kind === "uni" && hasFlag(s, "uni_paid")) fee = Math.round(250000 * (1 - D.wealth[s.wealth].fee));
      s.study = { kind: kind, field: e.study[1], left: e.study[2], fee: fee };
      delete s.flags.uni_paid;
    }
    if (e.getJob) {
      var cands;
      if (e.getJob === "field") cands = D.careers.filter(function (c) { return c.fields && c.fields.indexOf(s.field) >= 0 && eligible(s, c); });
      else if (e.getJob === "any") cands = ["courier", "build", "sales", "office", "taxi"].map(function (id) { return CAR[id]; }).filter(function (c) { return eligible(s, c); });
      else cands = [CAR[e.getJob]];
      if (!cands.length) cands = ["courier", "build"].map(function (id) { return CAR[id]; });
      var c = cands[0];
      if (cands.length > 1 && s.edu >= 2) c = cands.sort(function (a, b) { return (b.edu - a.edu) || (b.ladder[0][1] - a.ladder[0][1]); })[0];
      startJob(s, c.id);
      out.push("Тебя взяли: " + jobTitle(s).toLowerCase() + ", " + money(salary(s)) + " в месяц.");
    }
    if (e.partner === "new") newPartner(s);
    if (e.partner === "leave") divorce(s);
    if (e.partner === "die" && s.partner) { s.exes.push(s.partner.name); s.partner = null; }
    if (e.marry) pushEvent(s, "wedding", true);
    if (e.wed && s.partner) { s.partner.st = "married"; s.c.marriages++; s.partner.love = clamp(s.partner.love + 10, 0, 100); }
    if (e.tryBaby) { setFlag(s, "pregnant", 1); s.queue.push({ id: "baby_born", age: s.age + 1 }); }
    if (e.kid && ctx.kn) {
      var nm = ctx.kn[e.kid - 1];
      s.kids.push({ name: nm, g: ctx.kg, born: s.age });
      s.c.kidsTotal++;
      delete s.flags.pregnant;
      stat(s, "happy", 10);
      out.push(nm + " — самое громкое существо в доме. Ты счастлив[|а] и не выспал[ся|ась].");
    }
    if (e.loanCash) { addLoan(s, e.loanCash[0], e.loanCash[1], e.loanCash[2], e.loanCash[3]); cash(s, e.loanCash[1]); }
    if (e.debtMul) s.loans.forEach(function (l) { l.bal = Math.round(l.bal * e.debtMul); });
    if (e.bankrupt) bankrupt(s);
    if (e.ill) setFlag(s, "ill");
    if (e.cured) { if (hasFlag(s, "ill")) s.c.cured++; else s.c.cured++; delete s.flags.ill; }
    if (e.habit) for (var h in e.habit) s.habits[h] = e.habit[h] ? 1 : 0;
    if (e.stocksMul && s.stocks) { var sd = Math.round(s.stocks * (e.stocksMul - 1)); s.stocks += sd; fx(s, "net", sd); }
    if (e.bizMul && s.biz) s.biz.value = Math.round(s.biz.value * e.bizMul);
    if (e.houseMul && s.home.value) s.home.value = Math.round(s.home.value * e.houseMul);
    if (e.carLose && s.car) s.car = null;
    if (e.inherit) { var amt = inherit(s); out.push("Наследство: " + money(amt) + "."); }
    if (e.pIncome && s.partner) s.partner.inc = Math.round(s.partner.inc * e.pIncome);
    if (e.crypto) {
      var r = R(s), mul = r < 0.3 ? 0.08 : r < 0.6 ? 0.6 : r < 0.88 ? 2.2 : 9;
      var was = s.crypto, now = Math.round(was * mul);
      s.crypto = 0;
      cash(s, now);
      out.push(mul > 1 ? "Было " + money(was) + ", стало " + money(now) + ". Ты продаешь все и чувствуешь себя гением." : "Было " + money(was) + ", осталось " + money(now) + ". Ты удаляешь приложение.");
    }
    if (e.die) { s.cause = e.die; s.st.health = 0; }
    return gtext(s, out.join(" "), ctx);
  }

