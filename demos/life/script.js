  function act(s, id, key) {
    var a = ACT[id];
    if (!a || s.dead || s.pending.length || s.done[id]) return null;
    if (!rng2(a.a, s.age) || !ok(a.if, s)) return null;
    if (a.cost && s.cash < a.cost) return null;
    var opts = options(s, id);
    var opt = null;
    if (opts) {
      opt = opts.filter(function (o) { return o.key === key; })[0];
      if (!opt || !opt.ok) return null;
    }
    s.fx = {};
    s.done[id] = 1;
    var text = "";
    var ctx = {};
    if (!a.special) {
      ctx.m = effMoney(s, a.eff);
      var extra = applyEff(s, a.eff, ctx);
      text = gtext(s, pick(s, a.r), ctx) + (extra ? " " + extra : "");
    } else {
      text = special(s, a.special, key, ctx);
    }
    var it = log(s, "act", text, { a: a.e + " " + a.t + (opt ? ": " + opt.t.toLowerCase() : ""), fx: snapshotFx(s) });
    track(s);
    return it;
  }

