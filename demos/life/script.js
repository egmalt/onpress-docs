  function pushEvent(s, id, front) {
    var e = EV[id];
    if (!e) return;
    var ctx = {};
    if (e.if && !ok(e.if, s, ctx) && !e.q) return;
    if (id === "baby_born") {
      var g = R(s) < 0.5 ? "m" : "f";
      var pool = D.names[g].slice();
      ctx.kg = g;
      ctx.kn = [];
      for (var i = 0; i < 3; i++) ctx.kn.push(pool.splice(Math.floor(R(s) * pool.length), 1)[0]);
    }
    s.used[id] = (s.used[id] || 0) + 1;
    if (e.cd) s.cd[id] = s.age + e.cd;
    ctx.m = effMoney(s, e.eff) || (e.ch ? effMoney(s, e.ch[0].eff) : 0);
    if (!e.ch) {
      var text = gtext(s, e.t, ctx);
      var prev = s.fx;
      s.fx = {};
      var res = applyEff(s, e.eff, ctx);
      var own = snapshotFx(s);
      for (var k in own) prev[k] = (prev[k] || 0) + own[k];
      s.fx = prev;
      log(s, "ev", text + (res ? " " + res : ""), { fx: own });
      return;
    }
    var p = { id: id, t: gtext(s, e.t, ctx), ctx: ctx };
    if (front) s.pending.unshift(p); else s.pending.push(p);
  }
  function snapshotFx(s) {
    var o = {};
    for (var k in s.fx) if (s.fx[k]) o[k] = s.fx[k];
    return o;
  }

